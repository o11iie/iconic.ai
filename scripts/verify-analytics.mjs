/**
 * Gate 13 verification: learning analytics, in a real browser.
 *
 * Governing rule, unchanged since Gate 10:
 *
 *   A number appearing is NOT a pass.
 *
 * A dashboard that rendered constants would still show a retention figure. So
 * every check below asserts the number ON SCREEN equals a value computed by
 * hand from a known learner — not merely that a percentage is present.
 *
 * ## The reference learner
 *
 * Deterministic, never random, and shared with the unit tests via
 * `src/analytics/fixtures.ts` so the browser and the engine are asserted
 * against the SAME data:
 *
 *   Structure A  10 reviews,  8 recalled, 2 failed   -> retention 80%
 *   Structure B   5 reviews,  1 recalled, 4 failed   -> retention 20%
 *   Structure C   0 reviews                           -> untouched
 *
 *   15 reviews, 9 recalled                            -> overall 60%
 *   Structure A is a question (checkable), B a flashcard (self-rated), so
 *   accuracy is 8/10 = 80% over the 10 checkable reviews.
 *
 * ## What is real and what is substituted
 *
 * Real: the Next server, middleware, page, every component, the analytics
 * engine, the layout at six widths, the period filter, navigation.
 *
 * Substituted: Supabase. Auth is answered by `fixture-auth-server.mjs` so a
 * browser can be signed in, and `/api/analytics/*` is answered by route
 * interception carrying the engine's real output for the fixture learner.
 * Neither substitution touches VEO's source.
 *
 * Usage: node scripts/verify-analytics.mjs [baseUrl]
 */
import { chromium } from 'playwright';
import { authCookie } from './fixture-auth-server.mjs';

const BASE = process.argv[2] ?? process.env.VEO_BASE_URL ?? 'http://127.0.0.1:3411';
const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL ?? 'http://127.0.0.1:54330';

const IGNORED = [
  /Download the React DevTools/i,
  /\[Fast Refresh\]/i,
  /favicon\.ico/i,
  /fixture-auth-server implements auth only/i,
];

const results = { pass: 0, fail: 0, problems: [] };

function check(ok, label, detail = '') {
  if (ok) {
    results.pass += 1;
    console.log(`  PASS  ${label}`);
  } else {
    results.fail += 1;
    results.problems.push(`${label}${detail ? ` — ${detail}` : ''}`);
    console.log(`  FAIL  ${label}${detail ? ` — ${detail}` : ''}`);
  }
}

function captureConsole(page) {
  const errors = [];
  page.on('console', (m) => {
    if (m.type() !== 'error') return;
    const text = m.text();
    if (IGNORED.some((p) => p.test(text))) return;
    errors.push(text);
  });
  page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
  page.on('crash', () => errors.push('page crashed'));
  return errors;
}

async function signedInContext(browser, viewport) {
  const context = await browser.newContext({ viewport });
  const cookie = authCookie(SUPABASE_URL);
  await context.addCookies([
    { name: cookie.name, value: cookie.value, url: BASE, httpOnly: false, sameSite: 'Lax' },
  ]);
  return context;
}

const text = (page) => page.locator('main').innerText();

// ---------------------------------------------------------------------------
// The engine's real output, computed here so the browser is asserted against
// the same numbers the unit tests assert. Generated by `analytics-fixture.mjs`
// at build time and read from disk, so this harness never reimplements the
// engine — a second implementation would let both be wrong together.
// ---------------------------------------------------------------------------

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const FIXTURE = JSON.parse(
  readFileSync(join(process.cwd(), '.veo-analytics-fixture.json'), 'utf8'),
);

const EXPECTED = FIXTURE.expected;

function installAnalyticsApi(page, state) {
  return page.route('**/api/analytics/**', async (route) => {
    const url = new URL(route.request().url());
    const period = url.searchParams.get('period') ?? '30d';
    state.requests.push({ path: url.pathname, period });

    const payload = FIXTURE.byPeriod[period] ?? FIXTURE.byPeriod['30d'];

    const body = url.pathname.endsWith('/overview')
      ? { ok: true, overview: payload.overview }
      : url.pathname.endsWith('/knowledge-map')
        ? { ok: true, knowledgeMap: payload.knowledgeMap }
        : url.pathname.endsWith('/sessions')
          ? { ok: true, sessions: payload.sessions }
          : { ok: true, overview: payload.overview };

    return route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify(body),
    });
  });
}

function installEmptyApi(page) {
  return page.route('**/api/analytics/**', async (route) => {
    const url = new URL(route.request().url());
    const body = url.pathname.endsWith('/knowledge-map')
      ? { ok: true, knowledgeMap: FIXTURE.empty.knowledgeMap }
      : url.pathname.endsWith('/sessions')
        ? { ok: true, sessions: [] }
        : { ok: true, overview: FIXTURE.empty.overview };

    return route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify(body),
    });
  });
}

function freshState() {
  return { requests: [] };
}

// ---------------------------------------------------------------------------

async function main() {
  const browser = await chromium.launch({
    executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome',
    args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox'],
  });

  try {
    // =====================================================================
    console.log('\n=== 1. A NEW LEARNER IS TOLD THE TRUTH ===');
    // =====================================================================
    {
      const context = await signedInContext(browser, { width: 1440, height: 900 });
      const page = await context.newPage();
      const errors = captureConsole(page);
      await installEmptyApi(page);

      await page.goto(`${BASE}/analytics`, { waitUntil: 'networkidle' });
      const body = await text(page);

      check(!/\/login/.test(page.url()), 'a signed-in learner reaches /analytics', page.url());

      // The single most important honesty check in this gate.
      check(
        !/\b\d+\s*%/.test(body),
        'NO percentage is shown on an account with no reviews',
        body.match(/.{0,50}\d+\s*%.{0,30}/)?.[0] ?? '',
      );
      check(
        /No learning data yet/i.test(body),
        'it says there is no data rather than showing zeroes as measurements',
      );
      check(
        /will not invent/i.test(body),
        'and says plainly that it will not invent any',
      );
      check(
        /Explore in 3D/i.test(body) && /Build your review queue/i.test(body),
        'it offers real calls to action instead of statistics',
      );
      check(errors.length === 0, 'no console errors on the empty analytics page', errors.join(' | '));

      await context.close();
    }

    // =====================================================================
    console.log('\n=== 2. THE BROWSER SHOWS WHAT THE ENGINE COMPUTED ===');
    // =====================================================================
    {
      const context = await signedInContext(browser, { width: 1440, height: 900 });
      const page = await context.newPage();
      const errors = captureConsole(page);
      const state = freshState();
      await installAnalyticsApi(page, state);

      await page.goto(`${BASE}/analytics`, { waitUntil: 'networkidle' });
      await page.waitForSelector('[data-veo-analytics]');
      const body = await text(page);

      // Correspondence, against values computable by hand from the fixture.
      check(
        new RegExp(`\\b${EXPECTED.retentionPercent}\\s*%`).test(body),
        `overall retention shows ${EXPECTED.retentionPercent}% — 9 of 15 reviews recalled`,
        body.match(/.{0,40}%.{0,20}/)?.[0] ?? '',
      );
      check(
        new RegExp(`across ${EXPECTED.totalReviews} reviews`).test(body),
        `and names the ${EXPECTED.totalReviews} reviews it was computed from`,
      );
      check(
        new RegExp(`\\b${EXPECTED.totalReviews}\\b`).test(body),
        'activity reports the same review count as retention',
      );
      check(
        new RegExp(`${EXPECTED.questions} questions`).test(body) &&
          new RegExp(`${EXPECTED.flashcards} flashcards`).test(body),
        `questions and flashcards split ${EXPECTED.questions}/${EXPECTED.flashcards}`,
      );
      check(
        new RegExp(`\\b${EXPECTED.activeDays}\\b`).test(body),
        `active days shows ${EXPECTED.activeDays}`,
      );
      check(
        new RegExp(`${EXPECTED.structuresTracked} structures tracked`).test(body),
        `mastery tracks ${EXPECTED.structuresTracked} structures`,
      );

      // The weakest structure must lead the retention list.
      const weakestIndex = body.indexOf(EXPECTED.weakestName);
      const strongestIndex = body.indexOf(EXPECTED.strongestName);
      check(
        weakestIndex > -1 && strongestIndex > -1 && weakestIndex < strongestIndex,
        'the weakest structure is listed before the stronger one',
      );

      // An unstudied structure must not be presented as a failure.
      check(
        /not been studied yet/i.test(body) || /Not yet studied/i.test(body),
        'the unstudied structure is named as unstudied, not as weak',
      );

      // VEO must not invent a display name for a structure.
      check(
        !/Left Ventricle|Right Atrium|Aorta|Myocardium/i.test(body),
        'no invented anatomical name appears anywhere',
      );

      check(errors.length === 0, 'no console errors on the populated page', errors.join(' | '));
      await context.close();
    }

    // =====================================================================
    console.log('\n=== 3. EVERY FINDING CARRIES ITS EVIDENCE ===');
    // =====================================================================
    {
      const context = await signedInContext(browser, { width: 1440, height: 900 });
      const page = await context.newPage();
      const errors = captureConsole(page);
      await installAnalyticsApi(page, freshState());

      await page.goto(`${BASE}/analytics`, { waitUntil: 'networkidle' });
      await page.waitForSelector('[data-veo-analytics]');
      const body = await text(page);

      check(
        /reviews · \d+ lapses/i.test(body),
        'a flagged structure shows the reviews and lapses behind the flag',
      );
      check(
        /recall \d+% · mastery \d+%/i.test(body),
        'and the recall and mastery figures that produced it',
      );
      check(
        !/AI thinks|we think you|probably struggling/i.test(body),
        'no finding is asserted without evidence',
      );

      // Recommendations must explain themselves.
      const recommendations = await page.locator('[data-veo-recommendation]').count();
      check(recommendations > 0, `${recommendations} recommendations are shown`);

      const reasons = await page
        .locator('[data-veo-recommendation] p')
        .allInnerTexts();
      check(
        reasons.filter((line) => line.trim().length > 15).length >= recommendations,
        'every recommendation carries a reason in prose',
        JSON.stringify(reasons.slice(0, 3)),
      );

      check(errors.length === 0, 'no console errors', errors.join(' | '));
      await context.close();
    }

    // =====================================================================
    console.log('\n=== 4. THE PERIOD FILTER CHANGES THE FIGURES ===');
    // =====================================================================
    {
      const context = await signedInContext(browser, { width: 1440, height: 900 });
      const page = await context.newPage();
      const errors = captureConsole(page);
      const state = freshState();
      await installAnalyticsApi(page, state);

      await page.goto(`${BASE}/analytics`, { waitUntil: 'networkidle' });
      await page.waitForSelector('[data-veo-analytics]');

      const initial = await text(page);
      check(
        state.requests.every((request) => request.period === '30d'),
        'the page opens on the 30-day window',
        JSON.stringify(state.requests.map((r) => r.period)),
      );
      check(
        /Last 30 days/i.test(initial),
        'and says which window the figures cover',
      );

      // Switch to 7 days. The fixture's structure-B reviews all fall inside
      // the last 5 days, so the 7-day window sees fewer reviews than 30.
      state.requests.length = 0;
      await page.locator('[data-veo-period="7d"]').click();
      await page.waitForFunction(
        (expected) => document.body.innerText.includes(expected),
        `across ${EXPECTED.sevenDayReviews} reviews`,
        { timeout: 15_000 },
      );

      check(
        state.requests.every((request) => request.period === '7d'),
        'switching the filter refetches with the new period',
        JSON.stringify(state.requests.map((r) => r.period)),
      );

      const sevenDay = await text(page);
      check(
        new RegExp(`across ${EXPECTED.sevenDayReviews} reviews`).test(sevenDay),
        `the 7-day window shows its own ${EXPECTED.sevenDayReviews} reviews, not the 30-day figure`,
      );
      check(
        new RegExp(`\\b${EXPECTED.sevenDayRetentionPercent}\\s*%`).test(sevenDay),
        `and its own retention of ${EXPECTED.sevenDayRetentionPercent}%`,
      );
      check(
        EXPECTED.sevenDayReviews !== EXPECTED.totalReviews,
        'positive control: the two windows genuinely differ, so the check can fail',
      );

      // All time.
      await page.locator('[data-veo-period="all"]').click();
      await page.waitForFunction(
        () => document.body.innerText.includes('All time'),
        undefined,
        { timeout: 15_000 },
      );
      check(/All time/i.test(await text(page)), 'the all-time window is reachable');

      check(errors.length === 0, 'no console errors while filtering', errors.join(' | '));
      await context.close();
    }

    // =====================================================================
    console.log('\n=== 5. CHARTS RENDER, AND EMPTY BUCKETS STAY HONEST ===');
    // =====================================================================
    {
      const context = await signedInContext(browser, { width: 1440, height: 900 });
      const page = await context.newPage();
      const errors = captureConsole(page);
      await installAnalyticsApi(page, freshState());

      await page.goto(`${BASE}/analytics`, { waitUntil: 'networkidle' });
      await page.waitForSelector('[data-veo-analytics]');

      const paths = await page.locator('svg path[stroke]').count();
      check(paths > 0, `the retention trend renders ${paths} line segments`);

      // A day with no reviews must be a GAP, not a dive to zero. With reviews
      // on only some days, the line must be broken into several segments.
      check(
        paths >= EXPECTED.expectedTrendSegments,
        `the line breaks at gaps rather than diving to zero (${paths} segments)`,
        `expected at least ${EXPECTED.expectedTrendSegments}`,
      );

      // The table view exists, so the chart is not colour-alone.
      const tables = await page.getByText('View as table').count();
      check(tables > 0, `${tables} charts offer a table view`);

      await page.getByText('View as table').first().click();
      await page.waitForSelector('table');
      const tableText = await page.locator('table').first().innerText();
      check(
        /—/.test(tableText) || /\d/.test(tableText),
        'the table shows real values, with an em dash where there is no data',
      );

      check(errors.length === 0, 'no console errors with charts rendered', errors.join(' | '));
      await context.close();
    }

    // =====================================================================
    console.log('\n=== 6. UNAVAILABLE ANATOMY STAYS HONEST ===');
    // =====================================================================
    {
      const context = await signedInContext(browser, { width: 1440, height: 900 });
      const page = await context.newPage();
      const errors = captureConsole(page);
      await installAnalyticsApi(page, freshState());

      await page.goto(`${BASE}/analytics`, { waitUntil: 'networkidle' });
      await page.waitForSelector('[data-veo-analytics]');

      // Gate 9 is RED: no anatomy model loads, so the knowledge map must
      // offer no 3D action. A button that failed when tapped is worse than
      // no button.
      const mapActions = await page.locator('a:text-is("3D")').count();
      check(mapActions === 0, 'the knowledge map offers no 3D action for unavailable models');

      const body = await text(page);
      check(
        /Knowledge map/i.test(body),
        'but the knowledge map itself still renders without any model',
      );
      check(
        new RegExp(EXPECTED.mapRootName, 'i').test(body),
        'showing the learner\'s real structures',
      );

      // And the anatomy provider still reports itself unconfigured.
      const anatomy = await (await page.request.get(`${BASE}/api/anatomy`)).json();
      check(anatomy.configured === false, 'the anatomy provider still reports configured: false');
      check(anatomy.delivery === 'none', 'and delivery: none — Gate 9 is untouched');

      check(errors.length === 0, 'no console errors', errors.join(' | '));
      await context.close();
    }

    // =====================================================================
    console.log('\n=== 7. THE DASHBOARD AGREES WITH THE ANALYTICS PAGE ===');
    // =====================================================================
    {
      const context = await signedInContext(browser, { width: 1440, height: 900 });
      const page = await context.newPage();
      const errors = captureConsole(page);
      await installAnalyticsApi(page, freshState());

      await page.goto(`${BASE}/dashboard`, { waitUntil: 'networkidle' });
      await page.waitForSelector('[data-veo-dashboard-intelligence]', { timeout: 20_000 });
      const body = await text(page);

      check(
        new RegExp(`\\b${EXPECTED.retentionPercent}\\s*%`).test(body),
        `Home shows the same ${EXPECTED.retentionPercent}% retention as /analytics`,
      );
      check(
        new RegExp(`\\b${EXPECTED.totalReviews}\\b`).test(body),
        'and the same review count',
      );
      check(
        /Study next/i.test(body),
        'Home leads with what to study next',
      );
      check(
        await page.getByRole('link', { name: /Full analytics/i }).isVisible(),
        'and links through to the full analytics page',
      );

      // Navigation reaches it.
      await page.getByRole('link', { name: /Full analytics/i }).click();
      await page.waitForURL(/\/analytics/, { timeout: 20_000 });
      check(/\/analytics/.test(page.url()), 'the link navigates to /analytics', page.url());

      check(errors.length === 0, 'no console errors on the dashboard', errors.join(' | '));
      await context.close();
    }

    // =====================================================================
    console.log('\n=== 8. SIX VIEWPORTS ===');
    // =====================================================================
    {
      const VIEWPORTS = [
        { width: 1440, height: 900, name: 'desktop' },
        { width: 1024, height: 768, name: 'small laptop' },
        { width: 768, height: 1024, name: 'tablet' },
        { width: 430, height: 932, name: 'large phone' },
        { width: 390, height: 844, name: 'phone' },
        { width: 360, height: 800, name: 'small phone' },
      ];

      for (const viewport of VIEWPORTS) {
        const context = await signedInContext(browser, {
          width: viewport.width,
          height: viewport.height,
        });
        const page = await context.newPage();
        const errors = captureConsole(page);
        await installAnalyticsApi(page, freshState());

        await page.goto(`${BASE}/analytics`, { waitUntil: 'networkidle' });
        await page.waitForSelector('[data-veo-analytics]');

        // Measured by DISPLACEMENT, not scrollWidth: an element inside a
        // horizontal scroller inflates scrollWidth without the PAGE being
        // scrollable, and reporting that as overflow is a false alarm.
        const shift = await page.evaluate(async () => {
          window.scrollTo(9999, 0);
          await new Promise((r) => requestAnimationFrame(r));
          const x = window.scrollX;
          window.scrollTo(0, 0);
          return x;
        });
        check(
          shift === 0,
          `${viewport.name} ${viewport.width}px — no horizontal overflow`,
          `${shift}px`,
        );

        // The period filter must stay usable and on-screen.
        const buttons = await page.locator('[data-veo-period]').evaluateAll((nodes) =>
          nodes.map((n) => {
            const r = n.getBoundingClientRect();
            return { w: Math.round(r.width), h: Math.round(r.height), x: Math.round(r.left) };
          }),
        );
        check(buttons.length === 4, `${viewport.name} — all four periods are offered`);
        check(
          buttons.every((b) => b.h >= 28 && b.x >= 0 && b.x + b.w <= viewport.width + 1),
          `${viewport.name} — no period control is clipped`,
          JSON.stringify(buttons),
        );

        // Charts must not collapse to nothing. Targeted by an explicit hook,
        // not by DOM order: the first <svg> on the page is a nav icon, and
        // measuring that instead reported a 19px "chart" at every width.
        const charts = await page
          .locator('[data-veo-chart]')
          .evaluateAll((nodes) =>
            nodes.map((node) => {
              const rect = node.getBoundingClientRect();
              return { w: Math.round(rect.width), h: Math.round(rect.height) };
            }),
          );

        check(charts.length >= 2, `${viewport.name} — the charts render`, JSON.stringify(charts));
        check(
          charts.every((chart) => chart.h >= 60 && chart.w >= 120),
          `${viewport.name} — every chart keeps a readable size`,
          JSON.stringify(charts),
        );

        check(errors.length === 0, `${viewport.name} — no console errors`, errors.join(' | '));
        await context.close();
      }
    }

    // =====================================================================
    console.log('\n=== 9. NOTHING SECRET REACHES THE BROWSER ===');
    // =====================================================================
    {
      const context = await signedInContext(browser, { width: 1440, height: 900 });
      const page = await context.newPage();
      await installAnalyticsApi(page, freshState());

      const scripts = [];
      page.on('response', async (response) => {
        const type = response.headers()['content-type'] ?? '';
        if (!/javascript/.test(type)) return;
        try {
          scripts.push(await response.text());
        } catch {
          /* unreadable is not evidence either way */
        }
      });

      await page.goto(`${BASE}/analytics`, { waitUntil: 'networkidle' });
      await page.waitForSelector('[data-veo-analytics]');

      const bundle = scripts.join('\n');
      check(bundle.length > 10_000, 'the scan actually read the shipped bundles', `${bundle.length} bytes`);
      check(!/SUPABASE_SERVICE_ROLE/.test(bundle), 'no service-role key name in client code');
      check(!/sk-[A-Za-z0-9]{20,}/.test(bundle), 'no OpenAI-shaped key in client code');
      check(!/\bservice_role\b/.test(bundle), 'no service_role token in client code');

      await context.close();
    }
  } finally {
    await browser.close();
  }

  console.log(`\n${'='.repeat(60)}`);
  console.log(`VEO ANALYTICS VERIFICATION: ${results.pass} passed, ${results.fail} failed`);
  console.log('='.repeat(60));
  if (results.problems.length > 0) {
    console.log('\nProblems:');
    for (const problem of results.problems) console.log(`  - ${problem}`);
  }
  process.exit(results.fail === 0 ? 0 : 1);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
